// noSearchFixtureResource is a minimal resource with List.Search false
// (and no Filter) — the path the fixtureResource() golden never
// exercises, since it always has Search: true. Used to prove list-bar
// is gated on List.Search at generation time, not rendered
// unconditionally.
func noSearchFixtureResource() rastrillo.Resource {
	r := rastrillo.Resource{
		Name:  "widgets",
		Route: "/admin/widgets",
		Store: rastrillo.Exclusive,
		List: rastrillo.List{
			Columns: []rastrillo.Column{{Field: "Name"}},
			Search:  false,
		},
		Form: rastrillo.Form{
			Basics: []rastrillo.Field{{Name: "Name"}},
		},
	}
	if err := r.Validate(); err != nil {
		panic(err)
	}
	return r
}

// TestEmitTemplatesListHTMLGatesSearchOnFlag is the fix for a reviewer
// finding: list.html used to render the search box unconditionally,
// even though the generated store's WHERE clause only honors `q` when
// List.Search is true (whereClauses in store.go) — a search=false
// resource got a live-looking input that silently did nothing. list-bar
// is now gated on r.List.Search at GENERATION time (mirroring how
// hasAdvanced gates form.html's second form): a search=false resource's
// list.html contains no list-bar at all.
func TestEmitTemplatesListHTMLGatesSearchOnFlag(t *testing.T) {
	appRoot := t.TempDir()
	genDir := t.TempDir()
	r := noSearchFixtureResource()

	if _, _, err := EmitTemplates(appRoot, genDir, r); err != nil {
		t.Fatalf("EmitTemplates: %v", err)
	}

	got, err := os.ReadFile(filepath.Join(genDir, "templates", "widgets", "list.html"))
	if err != nil {
		t.Fatalf("read list.html: %v", err)
	}
	if strings.Contains(string(got), "list-bar") {
		t.Errorf("list.html contains \"list-bar\" for a Search: false resource:\n%s", got)
	}
	if strings.Contains(string(got), "rst-search") {
		t.Errorf("list.html contains \"rst-search\" for a Search: false resource:\n%s", got)
	}
	// The rows and the rst-list card wrapper must still be there — only
	// the search box is gone.
	if !strings.Contains(string(got), `<div class="rst-list">`) {
		t.Errorf("list.html lost its rst-list wrapper:\n%s", got)
	}
	if !strings.Contains(string(got), `{{range .Rows}}`) {
		t.Errorf("list.html lost its row range:\n%s", got)
	}
}

func TestEmitTemplatesGoldenFiles(t *testing.T) {
	appRoot := t.TempDir()
	genDir := t.TempDir()
	r := fixtureResource()

	written, skipped, err := EmitTemplates(appRoot, genDir, r)
	if err != nil {
		t.Fatalf("EmitTemplates: %v", err)
	}
	if len(skipped) != 0 {
		t.Fatalf("skipped = %v, want none", skipped)
	}
	wantWritten := []string{
		filepath.Join(genDir, "templates", "notes", "list.html"),
		filepath.Join(genDir, "templates", "notes", "show.html"),
		filepath.Join(genDir, "templates", "notes", "form.html"),
	}
	if len(written) != len(wantWritten) {
		t.Fatalf("written = %v, want %v", written, wantWritten)
	}
	for i := range wantWritten {
		if written[i] != wantWritten[i] {
			t.Errorf("written[%d] = %q, want %q", i, written[i], wantWritten[i])
		}
	}

	cases := []struct {
		path string
		want string
	}{
		{filepath.Join(genDir, "templates", "notes", "list.html"), goldenListHTML},
		{filepath.Join(genDir, "templates", "notes", "show.html"), goldenShowHTML},
		{filepath.Join(genDir, "templates", "notes", "form.html"), goldenFormHTML},
	}
	for _, c := range cases {
		got, err := os.ReadFile(c.path)
		if err != nil {
			t.Fatalf("read %s: %v", c.path, err)
		}
		if string(got) != c.want {
			t.Errorf("%s:\ngot:\n%s\nwant:\n%s", c.path, got, c.want)
		}
	}
}

