func TestEmitTemplatesSkipsEjectedFiles(t *testing.T) {
	appRoot := t.TempDir()
	genDir := t.TempDir()
	r := fixtureResource()

	handDir := filepath.Join(appRoot, "templates", "notes")
	if err := os.MkdirAll(handDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(handDir, "list.html"), []byte("hand-written"), 0o644); err != nil {
		t.Fatal(err)
	}

	written, skipped, err := EmitTemplates(appRoot, genDir, r)
	if err != nil {
		t.Fatalf("EmitTemplates: %v", err)
	}

	wantSkipped := []string{filepath.Join(genDir, "templates", "notes", "list.html")}
	if len(skipped) != 1 || skipped[0] != wantSkipped[0] {
		t.Fatalf("skipped = %v, want %v", skipped, wantSkipped)
	}
	if _, err := os.Stat(filepath.Join(genDir, "templates", "notes", "list.html")); !os.IsNotExist(err) {
		t.Fatalf("list.html was written into genDir despite the hand file")
	}

	wantWritten := []string{
		filepath.Join(genDir, "templates", "notes", "show.html"),
		filepath.Join(genDir, "templates", "notes", "form.html"),
	}
	if len(written) != len(wantWritten) {
		t.Fatalf("written = %v, want %v", written, wantWritten)
	}
	for i := range wantWritten {
		if written[i] != wantWritten[i] {
			t.Errorf("written[%d] = %q, want %q", i, written[i], wantWritten[i])
		}
	}
}

// TestEmittedTemplatesParse proves the emitted files compile as
// templates in exactly the environment the app provides them: ui's
// partials plus ui.Funcs() (dict/list/icon), plus a stubbed T (the app
// binds the real one per locale at request time; see localemw.go).
func TestEmittedTemplatesParse(t *testing.T) {
	appRoot := t.TempDir()
	genDir := t.TempDir()
	r := fixtureResource()

	if _, _, err := EmitTemplates(appRoot, genDir, r); err != nil {
		t.Fatalf("EmitTemplates: %v", err)
	}

	tmpl := template.New("").Funcs(ui.Funcs()).Funcs(template.FuncMap{
		"T": func(s string) string { return s },
	})
	tmpl, err := tmpl.ParseFS(ui.Templates(), "*.html")
	if err != nil {
		t.Fatalf("parse ui templates: %v", err)
	}
	tmpl, err = tmpl.ParseGlob(filepath.Join(genDir, "templates", "notes", "*.html"))
	if err != nil {
		t.Fatalf("parse emitted templates: %v", err)
	}
	if tmpl.Lookup("content") == nil {
		t.Fatalf("no \"content\" template defined after parsing")
	}
}

